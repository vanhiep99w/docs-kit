import { test, expect } from '@playwright/test';
test('click to load, interactive iframe, reset, source change and sandbox permissions', async ({page}) => {
  const requests = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {if(request.url().includes('/live-demo-document')) requests.push(request.url());});
  await page.goto('/?case=live-demo');
  await expect(page.locator('.live-demo')).toBeVisible();
  await expect(page.locator('.live-demo iframe')).toHaveCount(0);
  expect(requests).toHaveLength(0);
  await expect(page.getByRole('link',{name:'Source code ↗'})).toHaveAttribute('rel','noopener noreferrer');
  await page.getByRole('button',{name:'Chạy thử',exact:true}).focus();
  await page.keyboard.press('Enter');
  const iframe = page.locator('.live-demo iframe');
  await expect(iframe).toHaveAttribute('sandbox','allow-scripts allow-same-origin');
  await expect(iframe).toHaveAttribute('referrerpolicy','no-referrer');
  expect(await iframe.getAttribute('allow')).toBeNull();
  const frame = page.frameLocator('.live-demo iframe');
  await frame.getByRole('button',{name:'0',exact:true}).click();
  await expect(frame.getByRole('button',{name:'1',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Tải lại demo'}).click();
  await expect(frame.getByRole('button',{name:'0',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Đổi demo',exact:true}).click();
  await expect(iframe).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Chạy thử',exact:true})).toBeVisible();
  await expect(page.getByRole('link',{name:'Mở tab mới ↗'})).toHaveAttribute('href','/live-demo-document?other=1');
  expect(errors).toEqual([]);
});
test('fallback remains available without JavaScript', async ({browser}) => {
  const context = await browser.newContext({javaScriptEnabled:false});
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:4178/?case=live-demo');
  await expect(page.getByRole('link',{name:'Mở tab mới ↗'})).toBeVisible();
  await expect(page.locator('iframe')).toHaveCount(0);
  await context.close();
});
test('mobile, dark theme and externally blocked iframe keep recovery controls', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/?case=live-demo');
  const figure = page.locator('.live-demo');
  const light = await figure.evaluate(el => getComputedStyle(el).backgroundColor);
  await page.evaluate(() => document.documentElement.dataset.theme='dark');
  expect(await figure.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(light);
  await page.route('**/live-demo-document', route => route.abort());
  await page.getByRole('button',{name:'Chạy thử',exact:true}).click();
  await expect(page.getByRole('button',{name:'Tải lại demo'})).toBeVisible();
  await expect(page.getByRole('link',{name:'Mở tab mới ↗'})).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
